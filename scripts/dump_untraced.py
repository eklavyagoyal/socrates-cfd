"""Collect every number in LLM-written text that the numeric audit could not trace to the evidence package.

The audit (critic/audit.py) only says *that* a number is untraced. This script lists each one with its context
and a first, mechanical triage so the remainder can be classified by reading:

- convention: a confidence level or similar statistical convention (95 %, 99 %, 2σ), not a measured value;
- leakage-check: the value lies in the literature range of a requested quantity (Cd 1.25-1.45, St 0.155-0.175),
  where a memorised reference value would land; every such token must be read;
- other: anything else (typically arithmetic on package numbers: ratios, periods, percentages).

    python scripts/dump_untraced.py      # writes results/analysis/untraced_numbers.{json,md}
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCES = [("benchmark", REPO / "results" / "benchmark"), ("attacks", REPO / "results" / "attacks")]
LLM_SYSTEM = re.compile(r"^(L-judge|C-llm.*)$")
CONVENTION = re.compile(r"^(9[059]|68)(\.0+)?\s*%$|σ|sigma", re.I)
RANGES = {"Cd-like": (1.25, 1.45), "St-like": (0.155, 0.175)}


def value(token: str) -> float | None:
    m = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", token.replace("−", "-"))
    if not m:
        return None
    v = float(m.group())
    return v / 100 if token.strip().endswith("%") else v


def triage(token: str) -> str:
    if CONVENTION.search(token.strip()):
        return "convention"
    v = value(token)
    if v is not None and any(lo <= abs(v) <= hi for lo, hi in RANGES.values()):
        return "leakage-check"
    return "other"


def audits(obj, path=""):
    """Yield (json path, audit) for every numeric_audit in a result."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == "numeric_audit" and isinstance(v, dict):
                yield path, v
            else:
                yield from audits(v, f"{path}/{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from audits(v, f"{path}[{i}]")


def main() -> None:
    rows, traced = [], Counter()
    for phase, root in SOURCES:
        if not root.is_dir():
            continue
        for sysdir in sorted(p for p in root.iterdir() if p.is_dir() and LLM_SYSTEM.match(p.name)):
            for f in sorted(sysdir.glob("*.json")):
                if f.name.endswith(".partial.json"):
                    continue
                try:
                    r = json.loads(f.read_text())
                except json.JSONDecodeError as e:
                    raise SystemExit(f"unreadable result {f}: {e}")
                for where, a in audits(r):
                    traced[(phase, sysdir.name)] += a.get("traced") or 0
                    for u in a.get("untraced") or []:
                        rows.append({"phase": phase, "system": sysdir.name, "case": f.stem, "where": where,
                                     "token": u.get("token"), "context": u.get("context"),
                                     "triage": triage(u.get("token") or "")})
    out = REPO / "results" / "analysis"
    out.mkdir(parents=True, exist_ok=True)
    (out / "untraced_numbers.json").write_text(json.dumps(rows, indent=1))
    by = Counter((r["phase"], r["system"], r["triage"]) for r in rows)
    lines = ["# Untraced numbers in LLM text", "",
             "Generated by `scripts/dump_untraced.py`. Triage is mechanical; see the script docstring.", "",
             "| phase | system | traced | untraced | convention | leakage-check | other |", "|---|---|---|---|---|---|---|"]
    for phase, system in sorted({(r["phase"], r["system"]) for r in rows} | set(traced)):
        n = sum(by[(phase, system, t)] for t in ("convention", "leakage-check", "other"))
        lines.append(f"| {phase} | {system} | {traced[(phase, system)]} | {n} | {by[(phase, system, 'convention')]} | "
                     f"{by[(phase, system, 'leakage-check')]} | {by[(phase, system, 'other')]} |")
    lines += ["", "## Tokens to read (leakage-check first)", "", "| system | case | token | context |", "|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["triage"] != "leakage-check", r["triage"], r["system"], r["case"])):
        if r["triage"] == "convention":
            continue
        ctx = (r["context"] or "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {r['system']} | {r['case']} | `{r['token']}` ({r['triage']}) | {ctx} |")
    (out / "untraced_numbers.md").write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} untraced tokens; " + ", ".join(f"{k}: {v}" for k, v in
                                                      sorted(Counter(r['triage'] for r in rows).items())))


if __name__ == "__main__":
    sys.exit(main())
