"""Generate ``src/physis/solvers/lbm/triton_kernel.py`` from the D3Q19 constants.

Triton kernels must live in a real source file and are fully unrolled here (19 pulls,
moments, then one block per opposite pair), so writing them by hand invites a typo in a
sign or an index. Edit this generator, not the output:

    python scripts/gen_lbm_triton.py
"""

from __future__ import annotations

from pathlib import Path

from physis.solvers.lbm import lattice

OUT = Path(__file__).resolve().parents[1] / "src" / "physis" / "solvers" / "lbm" / "triton_kernel.py"


def _lin(coeffs: list[tuple[int, str]]) -> str:
    """Sum of +/- terms; '0.0' if empty."""
    parts = []
    for c, name in coeffs:
        if c == 0:
            continue
        parts.append(("+ " if c > 0 else "- ") + name if parts else ("" if c > 0 else "-") + name)
    return " ".join(parts) if parts else "0.0"


def _dot(c: tuple[int, int, int], a: str, b: str, d: str) -> str:
    return _lin([(c[0], a), (c[1], b), (c[2], d)])


def kernel_body() -> str:
    C, W, OPP = lattice.C, lattice.W, lattice.OPP
    L = []
    L.append("    idx = tl.program_id(0).to(tl.int64) * BLOCK + tl.arange(0, BLOCK).to(tl.int64)")
    L.append("    nx = NX.to(tl.int64)")
    L.append("    ny = NY.to(tl.int64)")
    L.append("    nz = NZ.to(tl.int64)")
    L.append("    n = nx * ny * nz")
    L.append("    mask = idx < n")
    L.append("    z = idx % nz")
    L.append("    y = (idx // nz) % ny")
    L.append("    x = idx // (ny * nz)")
    L.append("    me_solid = tl.load(solid + idx, mask=mask, other=1) != 0")
    for q, c in enumerate(C):
        L.append(f"    h{q} = _pull(hin, solid, {q}, {OPP[q]}, {c[0]}, {c[1]}, {c[2]}, x, y, z, nx, ny, nz, n, idx, mask)")
    L.append("    drho = " + " + ".join(f"h{q}" for q in range(lattice.Q)))
    for a, name in enumerate(("jx", "jy", "jz")):
        L.append(f"    {name} = " + _lin([(c[a], f"h{q}") for q, c in enumerate(C)]))
    L.append("    rho = 1.0 + drho")
    L.append("    fx = rho * gx")
    L.append("    fy = rho * gy")
    L.append("    fz = rho * gz")
    L.append("    ux = (jx + 0.5 * fx) / rho")
    L.append("    uy = (jy + 0.5 * fy) / rho")
    L.append("    uz = (jz + 0.5 * fz) / rho")
    L.append("    usq = ux * ux + uy * uy + uz * uz")
    L.append("    uf = ux * fx + uy * fy + uz * fz")
    L.append("    kp = 1.0 - 0.5 * wp")
    L.append("    km = 1.0 - 0.5 * wm")
    # rest population
    L.append(f"    eq0 = {W[0]!r} * (drho + rho * (-1.5 * usq))")
    L.append(f"    s0 = {W[0]!r} * (-3.0 * uf)")
    L.append("    _put(hout, 0, h0 - wp * (h0 - eq0) + kp * s0, idx, n, mask, me_solid)")
    # opposite pairs (a, b): cu_b = -cu_a, cf_b = -cf_a
    for a in range(1, lattice.Q, 2):
        b = OPP[a]
        c = C[a]
        w = W[a]
        L.append(f"    cu = {_dot(c, 'ux', 'uy', 'uz')}")
        L.append(f"    cf = {_dot(c, 'fx', 'fy', 'fz')}")
        L.append(f"    ep = {w!r} * (drho + rho * (4.5 * cu * cu - 1.5 * usq))")  # symmetric part of heq
        L.append(f"    em = {w!r} * (rho * 3.0 * cu)")                         # antisymmetric part
        L.append(f"    sp = {w!r} * (9.0 * cu * cf - 3.0 * uf)")
        L.append(f"    sm = {w!r} * (3.0 * cf)")
        L.append(f"    hp = 0.5 * (h{a} + h{b})")
        L.append(f"    hm = 0.5 * (h{a} - h{b})")
        L.append(f"    _put(hout, {a}, h{a} - wp * (hp - ep) - wm * (hm - em) + kp * sp + km * sm, idx, n, mask, me_solid)")
        L.append(f"    _put(hout, {b}, h{b} - wp * (hp - ep) + wm * (hm - em) + kp * sp - km * sm, idx, n, mask, me_solid)")
    return "\n".join(L)


TEMPLATE = '''"""Fused D3Q19 TRT step as one Triton kernel (NVIDIA GPUs, float32). GENERATED by
``scripts/gen_lbm_triton.py`` — edit the generator, not this file.

Same algorithm, state convention and direction order as :mod:`physis.solvers.lbm.trt` and
the Metal kernel. Pattern (pull helper, int64 offsets, BLOCK=512) follows
``benchmarks/hardware/bench_lbm_cuda.py``, which ran on the RTX 5090 with Triton 3.6.

This kernel was written on a Mac without an NVIDIA GPU. :func:`selfcheck` compares it with
the torch reference on the same device before it is used; :mod:`physis.solvers.lbm.periodic`
only takes the Triton path when that check passes.
"""

from __future__ import annotations

import functools

import torch

try:
    import triton
    import triton.language as tl

    HAVE_TRITON = True
    TRITON_ERROR = ""
except Exception as exc:  # noqa: BLE001 - any import failure means "no Triton"
    HAVE_TRITON = False
    TRITON_ERROR = f"{type(exc).__name__}: {exc}"

BLOCK = 512


def available() -> bool:
    return HAVE_TRITON and torch.cuda.is_available()


if HAVE_TRITON:

    @triton.jit
    def _pull(hin, solid, q: tl.constexpr, o: tl.constexpr, cx: tl.constexpr, cy: tl.constexpr,
              cz: tl.constexpr, x, y, z, nx, ny, nz, n, idx, mask):
        xs = (x - cx + nx) % nx
        ys = (y - cy + ny) % ny
        zs = (z - cz + nz) % nz
        s = (xs * ny + ys) * nz + zs
        src_solid = tl.load(solid + s, mask=mask, other=0) != 0
        pulled = tl.load(hin + q * n + s, mask=mask & (src_solid == 0), other=0.0)
        bounced = tl.load(hin + o * n + idx, mask=mask & src_solid, other=0.0)
        return tl.where(src_solid, bounced, pulled)

    @triton.jit
    def _put(hout, q: tl.constexpr, val, idx, n, mask, me_solid):
        tl.store(hout + q * n + idx, tl.where(me_solid, 0.0, val), mask=mask)

    @triton.jit
    def trt_step_kernel(hin, hout, solid, NX, NY, NZ, wp, wm, gx, gy, gz, BLOCK: tl.constexpr):
__BODY__


class TritonStepper:
    """Persistent double buffer plus the device constants for one solid mask (CUDA, float32)."""

    def __init__(self, solid: torch.Tensor, h0: torch.Tensor):
        if not available():
            raise RuntimeError(f"Triton fast path unavailable: {TRITON_ERROR or 'no CUDA device'}")
        self.solid = solid.to(device=h0.device, dtype=torch.uint8).contiguous()
        self.shape = tuple(int(v) for v in solid.shape)
        self.n = self.solid.numel()
        self.a = h0.to(torch.float32).contiguous()
        self.b = torch.empty_like(self.a)

    @property
    def state(self) -> torch.Tensor:
        return self.a

    def run(self, steps: int, g, omega_p: float, omega_m: float) -> torch.Tensor:
        gx, gy, gz = (float(v) for v in g)
        nx, ny, nz = self.shape
        grid = (triton.cdiv(self.n, BLOCK),)
        for _ in range(steps):
            trt_step_kernel[grid](self.a, self.b, self.solid, nx, ny, nz, float(omega_p), float(omega_m),
                                  gx, gy, gz, BLOCK=BLOCK)
            self.a, self.b = self.b, self.a
        return self.a


@functools.lru_cache(maxsize=4)
def selfcheck(device: str = "cuda") -> tuple[bool, str]:
    """Run 7 steps of a small random case with the kernel and with the float64 torch
    reference; pass when populations agree to float32 precision."""
    if not available():
        return False, f"unavailable: {TRITON_ERROR or 'no CUDA device'}"
    from physis.core.backend import get_backend
    from physis.solvers.lbm import lattice, trt

    try:
        gen = torch.Generator().manual_seed(7)
        shape = (11, 9, 7)
        solid = torch.rand(shape, generator=gen) < 0.25
        h = 1e-3 * torch.randn(19, *shape, generator=gen, dtype=torch.float64)
        h[:, solid] = 0.0
        g = (1e-5, -2e-6, 3e-6)
        wp, wm = 1 / 0.9, 1 / lattice.tau_minus(0.9)
        cpu = get_backend("validation", device="cpu")
        ref_lat = trt.Lattice(solid, cpu)
        ref = h
        for _ in range(7):
            ref = ref_lat.step(ref, cpu.tensor(g), wp, wm)
        st = TritonStepper(solid, h.to(device=device, dtype=torch.float32))
        got = st.run(7, g, wp, wm).double().cpu()
        torch.cuda.synchronize()
        err = float((got - ref).abs().max())
        scale = float(ref.abs().max())
        ok = err <= 1e-5 * scale + 1e-9 and bool(torch.isfinite(got).all())
        return bool(ok), f"max abs diff {err:.3e} (reference scale {scale:.3e})"
    except Exception as exc:  # noqa: BLE001 - a crashing kernel is a failed check, not a crash of the run
        return False, f"{type(exc).__name__}: {exc}"
'''


def main() -> None:
    body = "\n".join("    " + line for line in kernel_body().splitlines())  # inside `if HAVE_TRITON:`
    OUT.write_text(TEMPLATE.replace("__BODY__", body) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
