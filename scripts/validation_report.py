"""Aggregate validation/results/*.json into docs/validation.md.

A gate is reported as STALE when the source fingerprint stored with its result differs
from the current fingerprint of its subpackage: the PASS was earned by different code.

    python scripts/validation_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

from physis.core.provenance import REPO_ROOT, source_fingerprint

RESULTS = REPO_ROOT / "validation" / "results"
OUT = REPO_ROOT / "docs" / "validation.md"


def _fmt(v: float) -> str:
    return f"{v:.4g}"


def main() -> int:
    records = [json.loads(p.read_text()) for p in sorted(RESULTS.glob("*.json"))]
    lines = [
        "# Validation status",
        "",
        "Generated by `scripts/validation_report.py` from `validation/results/*.json`. Do not edit by hand.",
        "A capability is validated only while its gate is **PASS** on the current code; **STALE** means the",
        "stored result was produced by a different version of the solver's source.",
        "",
        "| Gate | Capability | Status | Checks | Reference | Run |",
        "|---|---|---|---|---|---|",
    ]
    n_pass = 0
    for r in records:
        status = r["status"]
        sub = r.get("code", {}).get("subpackage", "")
        if status == "PASS" and r.get("code", {}).get("fingerprint") != source_fingerprint(sub):
            status = "STALE"
        n_pass += status == "PASS"
        checks = "<br>".join(
            f"{'✓' if c['pass'] else '✗'} {c['name']}: {_fmt(c['value'])} {c['op']} {_fmt(c['limit'])}"
            for c in r.get("checks", [])
        )
        ref = r.get("reference", {}).get("source", "")
        lines.append(
            f"| `{r['gate']}` | {r['capability']} | **{status}** | {checks} | {ref} | "
            f"{r.get('timestamp', '')}, {r.get('wall_time_s', '')} s, {r.get('backend', {}).get('dtype', '')} |"
        )
    lines += ["", f"{n_pass} of {len(records)} gates pass on the current code.", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {n_pass}/{len(records)} PASS")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
