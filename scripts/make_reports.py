"""Assemble reports/benchmark_results.md from stored results (run analyze_benchmark.py first).

Every number is read from results/ files; the narrative sections that interpret them live in
reports/final_report.md and are written by hand from these tables.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from socrates.orchestration.store import RunStore  # noqa: E402

BENCH = REPO / "results" / "benchmark"
ATT = REPO / "results" / "attacks"


def fmt(x, nd=4):
    if x is None:
        return "—"
    if isinstance(x, float):
        return f"{x:.{nd}g}"
    return str(x)


def loop_trace(store: RunStore, r: dict, qs: list[str]) -> list[str]:
    out = []
    for h in r.get("history") or []:
        ne = h.get("next_experiment") or {}
        dec = h.get("decision") or ("review" if h.get("review") else "")
        out.append(f"  - it{h.get('iteration')}: verdict {h.get('deterministic_verdict', '?')} → {dec} "
                   f"{ne.get('action', '')} {ne.get('parameters') or ''} — {h.get('outcome', '')}")
    for e in r.get("experiments") or []:
        if not e.get("run_id"):
            continue
        try:
            child = (store.load(e["run_id"]).evidence or {}).get("qoi", {}).get("stationary") or {}
            parent = (store.load(e["parent_run"]).evidence or {}).get("qoi", {}).get("stationary") or {}
        except (OSError, KeyError):
            continue
        ch = []
        for q in qs:
            a, b = parent.get(q), child.get(q)
            if a and b:
                ch.append(f"{q.split('_')[0]} {a:.4f}→{b:.4f} ({(b - a) / a:+.2%})")
        out.append(f"  - `{e['action']}` → `{e['run_id']}`: " + "; ".join(ch))
    return out


def main() -> None:
    store = RunStore(REPO / "results" / "runs")
    labels = json.loads((REPO / "benchmark" / "labels.json").read_text())
    qs = ["mean_drag_coefficient", "strouhal_number"]
    tables = (REPO / "reports" / "benchmark_tables.md").read_text()
    L = ["# Benchmark results", "",
         "_Generated by `scripts/make_reports.py` from `results/`. Interpretation: `reports/final_report.md`._", "",
         "## Ground truth", "",
         f"In-house converged reference (baseline one-factor refinement chains, Richardson-extrapolated; "
         f"`reports/baseline_validation.md`): "
         + ", ".join(f"{q} = {labels['truth'][q]:.4f} (±{labels['truth_uncertainty_rel'][q]:.2%})" for q in qs) + ".",
         "", f"Labelling rule (pre-registered): {labels['rule']}; label unstable under the truth uncertainty → ambiguous.", "",
         "| case | intended | measured label | reported Cd | reported St | err Cd | err St | note |",
         "|---|---|---|---|---|---|---|---|"]
    for cid, lab in labels["cases"].items():
        if lab.get("label") == "unrun":
            continue
        e = lab.get("errors", {})
        rep = lab.get("reported", {})
        note = "; ".join(lab.get("setup_problems") or []) or (("unstable: " + ",".join(lab["label_unstable"]))
                                                                 if lab.get("label_unstable") else "")
        L.append(f"| {cid} | {lab['intended']} | **{lab['label']}** | {fmt(rep.get(qs[0]))} | {fmt(rep.get(qs[1]))} | "
                 f"{fmt(e.get(qs[0]) and 100 * e[qs[0]], 3)}% | {fmt(e.get(qs[1]) and 100 * e[qs[1]], 3)}% | {note} |")
    L += ["", "## Verdicts and pre-registered rates", "", tables, "",
          "![verdict matrix](figures/verdict_matrix.png)", "", "![rates](figures/rates.png)", "",
          "![cost vs detection](figures/cost_vs_detection.png)", "", "## Adaptive-loop traces", ""]
    for cid in labels["cases"]:
        for s in ("C-rule", "C-llm"):
            f = BENCH / s / f"{cid}.json"
            if not f.exists():
                continue
            r = json.loads(f.read_text())
            L.append(f"**{cid} — {s}: {r.get('final_verdict') or r.get('verdict')}** "
                     f"({r.get('stop_reason', '')}; {len([e for e in r.get('experiments') or [] if e.get('run_id')])} experiments, "
                     f"{fmt((r.get('cost') or {}).get('relative_to_root'), 3)}× root compute)")
            L += loop_trace(store, r, qs)
            L.append("")
    L += ["## LLM judge (evidence only, no experiments, no checks) — reasoning excerpts", ""]
    for cid in labels["cases"]:
        f = BENCH / "L-judge" / f"{cid}.json"
        if f.exists():
            r = json.loads(f.read_text())
            first = (r.get("reasoning_summary") or [""])[-1]
            L.append(f"- **{cid}: {r.get('verdict')}** ({r.get('confidence')}) — {first[:300]}")
    if ATT.exists():
        L += ["", "## Attacks on the verifier", "", "| attack | " + " | ".join(
            s for s in ["B-v1", "C-rule-v1", "C-llm-v1", "C-llm-v1+review", "B-v2", "C-rule-v2"]) + " |",
              "|---|" + "---|" * 6]
        for f in sorted((REPO / "cases" / "attacks").glob("*.yaml")):
            row = []
            for s in ["B-v1", "C-rule-v1", "C-llm-v1", "C-llm-v1+review", "B-v2", "C-rule-v2"]:
                g = ATT / s / f"{f.stem}.json"
                row.append((json.loads(g.read_text()).get("final_verdict") or json.loads(g.read_text()).get("verdict"))
                           if g.exists() else "—")
            L.append(f"| {f.stem} | " + " | ".join(row) + " |")
    (REPO / "reports" / "benchmark_results.md").write_text("\n".join(L) + "\n")
    print("wrote reports/benchmark_results.md")


if __name__ == "__main__":
    main()
