"""Write a complete OpenFOAM (ESI v2412) case directory from a CaseConfig.

Every file is generated; nothing is copied from hand-edited templates, so a
case is fully determined by (CaseConfig, OpenFOAM version).  The generator
also writes ``case_config.json`` into the case so the exact configuration
travels with the raw solver output.
"""

from __future__ import annotations

import json
from pathlib import Path

from .blockmesh import BlockLayout, render_blockmesh_dict
from .spec import CaseConfig

HEADER = """FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


def _hdr(cls: str, obj: str) -> str:
    return "/* Generated by socrates.case_generation.writer */\n" + HEADER.format(cls=cls, obj=obj)


def _g(x: float) -> str:
    return f"{x:.10g}"


def _velocity_file(cfg: CaseConfig) -> str:
    U = cfg.physical.inlet_velocity
    b = cfg.boundaries
    lateral = {
        "symmetryPlane": "        type symmetryPlane;",
        "slip": "        type slip;",
        "noSlipWall": "        type noSlip;",
        "zeroGradientPatch": "        type zeroGradient;",
    }[b.lateral]
    outlet = (
        f"        type inletOutlet;\n        inletValue uniform (0 0 0);\n        value uniform ({_g(U)} 0 0);"
        if b.outlet_velocity == "inletOutlet"
        else "        type zeroGradient;"
    )
    cyl = "        type noSlip;" if b.cylinder_velocity == "noSlip" else "        type slip;"
    return (
        _hdr("volVectorField", "U")
        + f"""
dimensions      [0 1 -1 0 0 0 0];

internalField   uniform ({_g(U)} 0 0);

boundaryField
{{
    inlet
    {{
        type fixedValue;
        value uniform ({_g(U)} 0 0);
    }}
    outlet
    {{
{outlet}
    }}
    cylinder
    {{
{cyl}
    }}
    top
    {{
{lateral}
    }}
    bottom
    {{
{lateral}
    }}
    frontAndBack
    {{
        type empty;
    }}
}}
"""
    )


def _pressure_file(cfg: CaseConfig) -> str:
    b = cfg.boundaries
    lateral = {
        "symmetryPlane": "        type symmetryPlane;",
        "slip": "        type zeroGradient;",
        "noSlipWall": "        type zeroGradient;",
        "zeroGradientPatch": "        type zeroGradient;",
    }[b.lateral]
    inlet = "        type zeroGradient;" if b.inlet_pressure == "zeroGradient" else "        type fixedValue;\n        value uniform 0;"
    outlet = "        type fixedValue;\n        value uniform 0;" if b.outlet_pressure == "fixedValue" else "        type zeroGradient;"
    return (
        _hdr("volScalarField", "p")
        + f"""
dimensions      [0 2 -2 0 0 0 0];

internalField   uniform 0;

boundaryField
{{
    inlet
    {{
{inlet}
    }}
    outlet
    {{
{outlet}
    }}
    cylinder
    {{
        type zeroGradient;
    }}
    top
    {{
{lateral}
    }}
    bottom
    {{
{lateral}
    }}
    frontAndBack
    {{
        type empty;
    }}
}}
"""
    )


def _transport(cfg: CaseConfig) -> str:
    return _hdr("dictionary", "transportProperties") + (
        f"\ntransportModel  Newtonian;\n\nnu              {_g(cfg.physical.kinematic_viscosity)};\n"
    )


def _turbulence() -> str:
    return _hdr("dictionary", "turbulenceProperties") + "\nsimulationType  laminar;\n"


def _function_objects(cfg: CaseConfig) -> str:
    ref = cfg.resolved_force_reference()
    steady = cfg.numerics.solver == "simpleFoam"
    flux_fields = "\n".join(
        f"""    flux_{p}
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            {p};
        operation       sum;
        fields          (phi);
        writeFields     false;
        log             false;
        writeControl    timeStep;
        writeInterval   {1 if steady else 20};
    }}"""
        for p in ("inlet", "outlet", "top", "bottom")
    )
    return f"""functions
{{
    forceCoeffs1
    {{
        type            forceCoeffs;
        libs            (forces);
        writeControl    timeStep;
        writeInterval   1;
        log             false;
        patches         (cylinder);
        rho             rhoInf;
        rhoInf          {_g(ref['rhoInf'])};
        CofR            (0 0 0);
        liftDir         (0 1 0);
        dragDir         (1 0 0);
        pitchAxis       (0 0 1);
        magUInf         {_g(ref['magUInf'])};
        lRef            {_g(ref['lRef'])};
        Aref            {_g(ref['Aref'])};
    }}

    solverInfo1
    {{
        type            solverInfo;
        libs            (utilityFunctionObjects);
        fields          (U p);
        writeResidualFields false;
        writeControl    timeStep;
        writeInterval   1;
    }}

{flux_fields}
}}
"""


def _control_dict(cfg: CaseConfig) -> str:
    tc = cfg.convective_time
    t = cfg.time
    if cfg.numerics.solver == "simpleFoam":
        body = f"""
application     simpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {cfg.numerics.steady_iterations};
deltaT          1;
writeControl    timeStep;
writeInterval   {cfg.numerics.steady_iterations};
purgeWrite      0;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   8;
runTimeModifiable false;
"""
    else:
        adjust = "yes" if t.adjust_time_step else "no"
        body = f"""
application     pimpleFoam;
startFrom       latestTime;
startTime       0;
stopAt          endTime;
endTime         {_g(t.end_time * tc)};
deltaT          {_g(t.delta_t * tc)};
adjustTimeStep  {adjust};
maxCo           {_g(t.max_co)};
maxDeltaT       {_g(t.delta_t * tc)};
writeControl    {'adjustable' if t.adjust_time_step else 'runTime'};
writeInterval   {_g(t.write_interval * tc)};
purgeWrite      0;
writeFormat     ascii;
writePrecision  10;
writeCompression off;
timeFormat      general;
timePrecision   10;
runTimeModifiable false;
"""
    return _hdr("dictionary", "controlDict") + body + "\n" + _function_objects(cfg)


def _fv_schemes(cfg: CaseConfig) -> str:
    n = cfg.numerics
    ddt = "steadyState" if n.solver == "simpleFoam" else n.ddt
    div_u = n.div_U
    if n.solver == "simpleFoam" and not div_u.startswith("bounded"):
        div_u = "bounded " + div_u
    return _hdr("dictionary", "fvSchemes") + f"""
ddtSchemes
{{
    default         {ddt};
}}

gradSchemes
{{
    default         {n.grad};
}}

divSchemes
{{
    default         none;
    div(phi,U)      {div_u};
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}

laplacianSchemes
{{
    default         {n.laplacian};
}}

interpolationSchemes
{{
    default         linear;
}}

snGradSchemes
{{
    default         corrected;
}}
"""


def _fv_solution(cfg: CaseConfig) -> str:
    n = cfg.numerics
    if n.solver == "simpleFoam":
        algo = f"""
SIMPLE
{{
    nNonOrthogonalCorrectors {n.n_nonorth_correctors};
    consistent      no;
    residualControl
    {{
        p               {_g(n.steady_residual_target)};
        U               {_g(n.steady_residual_target)};
    }}
}}

relaxationFactors
{{
    fields
    {{
        p               {_g(n.relax_p)};
    }}
    equations
    {{
        U               {_g(n.relax_U)};
    }}
}}
"""
    else:
        algo = f"""
PIMPLE
{{
    nOuterCorrectors {n.n_outer_correctors};
    nCorrectors     {n.n_correctors};
    nNonOrthogonalCorrectors {n.n_nonorth_correctors};
}}
"""
    return _hdr("dictionary", "fvSolution") + f"""
solvers
{{
    p
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-07;
        relTol          0.01;
    }}

    pFinal
    {{
        $p;
        relTol          0;
    }}

    "(U|UFinal)"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-08;
        relTol          0;
    }}
}}
{algo}"""


def _set_fields(cfg: CaseConfig) -> str:
    p = cfg.perturbation
    D = cfg.physical.diameter
    U = cfg.physical.inlet_velocity
    span = cfg.mesh.span * D
    return _hdr("dictionary", "setFieldsDict") + f"""
defaultFieldValues
(
    volVectorFieldValue U ({_g(U)} 0 0)
);

regions
(
    boxToCell
    {{
        box ({_g(p.box_min[0] * D)} {_g(p.box_min[1] * D)} {_g(-span)}) ({_g(p.box_max[0] * D)} {_g(p.box_max[1] * D)} {_g(2 * span)});
        fieldValues
        (
            volVectorFieldValue U ({_g(U)} {_g(p.v_fraction * U)} 0)
        );
    }}
);
"""


def write_case(cfg: CaseConfig, case_dir: str | Path) -> BlockLayout:
    """Create ``case_dir`` (must not contain a previous case) and write all files."""
    case_dir = Path(case_dir)
    for sub in ("0", "constant", "system"):
        (case_dir / sub).mkdir(parents=True, exist_ok=True)
    bm_text, layout = render_blockmesh_dict(cfg)
    files = {
        "system/blockMeshDict": bm_text,
        "system/controlDict": _control_dict(cfg),
        "system/fvSchemes": _fv_schemes(cfg),
        "system/fvSolution": _fv_solution(cfg),
        "system/setFieldsDict": _set_fields(cfg),
        "0/U": _velocity_file(cfg),
        "0/p": _pressure_file(cfg),
        "constant/transportProperties": _transport(cfg),
        "constant/turbulenceProperties": _turbulence(),
    }
    for rel, text in files.items():
        (case_dir / rel).write_text(text)
    (case_dir / "case_config.json").write_text(json.dumps(cfg.model_dump(mode="json"), indent=2))
    return layout
